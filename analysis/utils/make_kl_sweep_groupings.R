# make_kl_sweep_groupings.R — prior registries of the brms_kl class sweep (K = 2, 3, 4)
#
# Non-step tool (no phase number; see analysis/utils/README.md §3). Builds the
# kernel.prior_grouping registries of analysis/configs/kl_sweep_classes/ by
# merging whole groups of analysis/groupings/enso_grouping.csv (no country is
# moved on its own). Under kernel.identify seed, K = the registry groups present
# among the fitted countries and every group gets a seed, so each K needs a
# registry with exactly K groups. The merges follow the rainy season ENSO acts
# on (austral summer / short rains: East, South; boreal-summer monsoon: West,
# Horn, NGA) and the class centres of kl_full_gauss_seed5_sdc0p2_mem (East ~0,
# South ~2, West ~4.5, Horn ~9.5, NGA ~10):
#   K = 2  enso_east  <- east + south                 (seed TZA)
#          enso_west  <- west + horn + central        (seed NER)
#   K = 3  enso_east, enso_south, enso_west <- west + horn + central
#   K = 4  enso_east, enso_south, enso_horn, enso_west <- west + central
#   K = 5  enso_grouping_nga (existing, not written here)
# NGA stays in enso_west for K <= 4. Central (GAB, GNQ, STP) is not fitted; it
# is folded into enso_west so that a fitted central country cannot add an
# auto-seeded class. Group order in each CSV (= class order) follows the
# first appearance in enso_grouping.csv. Writes analysis/groupings/
# enso_grouping_k<K>.csv (+ .yml display sidecar), validated by reading back
# with load_grouping() / load_grouping_meta().
#
# Run (repo root):
#   Rscript analysis/utils/make_kl_sweep_groupings.R [--force]

suppressPackageStartupMessages(library(optparse))
args <- parse_args(OptionParser(option_list = list(
  make_option("--force", default = FALSE, action = "store_true",
              help = "overwrite existing analysis/groupings/enso_grouping_k<K>.{csv,yml}")
)))
for (m in c("base", "config")) source(sprintf("analysis/utils/%s.R", m))

SRC  <- "enso_grouping"
GDIR <- "analysis/groupings"

# source group -> sweep group, per K
MERGES <- list(
  k2 = c(enso_east = "enso_east", enso_south = "enso_east",
         enso_west = "enso_west", enso_horn = "enso_west", enso_central = "enso_west"),
  k3 = c(enso_east = "enso_east", enso_south = "enso_south",
         enso_west = "enso_west", enso_horn = "enso_west", enso_central = "enso_west"),
  k4 = c(enso_east = "enso_east", enso_south = "enso_south",
         enso_west = "enso_west", enso_horn = "enso_horn", enso_central = "enso_west")
)

reg  <- load_grouping(SRC, GDIR)
meta <- load_grouping_meta(SRC, GDIR)
miss <- setdiff(unique(reg$group), names(MERGES[[1]]))
if (length(miss)) stop("groups of ", SRC, " with no merge rule: ", paste(miss, collapse = ", "))

for (k in names(MERGES)) {
  mp  <- MERGES[[k]]
  out <- paste0(SRC, "_", k)
  csv <- registry_path(out, GDIR)
  yml <- registry_path(out, GDIR, "yml")
  if (!args$force && (file.exists(csv) || file.exists(yml)))
    stop(csv, " or its sidecar exists (use --force to overwrite).")

  new <- data.frame(iso3 = reg$iso3, group = unname(mp[reg$group]), stringsAsFactors = FALSE)
  utils::write.csv(new, csv, row.names = FALSE, quote = FALSE)

  # Sidecar: a merged group is labelled after its members ("East + Southern Africa").
  groups <- unique(new$group)
  side <- list(label_prefix = "enso_", order = as.list(groups), groups = list())
  for (g in groups) {
    members <- names(mp)[mp == g]
    members <- members[members %in% unique(reg$group) & members != "enso_central"]
    side$groups[[g]] <- list(
      label     = paste(meta$label[members], collapse = " + "),
      short     = paste(meta$short[members], collapse = "+"),
      short_fig = paste(meta$short_fig[members], collapse = "+"),
      colour    = unname(meta$colour[g]))
  }
  hdr <- c(sprintf("# Display metadata for %s.csv (utils/config.R::load_grouping_meta()).", out),
           "# Generated by analysis/utils/make_kl_sweep_groupings.R from enso_grouping.csv",
           "# (whole groups merged; central folded into enso_west). Do not edit by hand.")
  writeLines(c(hdr, yaml::as.yaml(side)), yml)

  chk <- load_grouping(out, GDIR); load_grouping_meta(out, GDIR)
  stopifnot(identical(chk$iso3, reg$iso3), length(unique(chk$group)) == as.integer(sub("k", "", k)))
  cat(sprintf("Wrote %s (%s)\n", csv,
              paste(sprintf("%s %d", names(table(chk$group)), table(chk$group)), collapse = ", ")))
}

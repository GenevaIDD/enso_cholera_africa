#!/usr/bin/env Rscript
# deploy_prod_run.R — deployment orchestrator: wires configs and collects fits
#   for one run from its deploy YAML; prints, never submits, the HPC commands.
#
# Usage:
#   D=analysis/configs/deploy/prod_run.yml
#   Rscript analysis/utils/deploy_prod_run.R -C $D --stage all --dry-run
#   Rscript analysis/utils/deploy_prod_run.R -C $D --stage resolve
#   Rscript analysis/utils/deploy_prod_run.R -C $D --stage gen_forecast \
#     --align-results
#
# Details:
#   Non-step tool: runs between phases 05 and 07 (deploy_fits after the LOO
#   lag ranking, gen_forecast / gen_hindcast after the 08 smoothing cache).
#   Stages (--stage): gen_batches, gen_grouping, deploy_fits, gen_templates,
#   smoothing, gen_forecast, gen_attrib, gen_hindcast, gen_events,
#   align_results, all, resolve; --dry-run writes
#   nothing, --force overwrites a differing generated file.
#   The run tag is the deploy YAML's filename; provenance lands in
#   generated_data/deploy/<stem>/.


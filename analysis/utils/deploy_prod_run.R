# ---------------------------------------------------------------------------
# Stage: gen_batches  (R logic, in-process; honours --dry-run) -> PRINT fit cmds
# ---------------------------------------------------------------------------
stage_gen_batches <- function() {
  say("[deploy] STAGE gen_batches%s", if (DRY) " (dry-run)" else "")
  rule()
  env <- deploy_batch_env()
  plan <- deploy_plan_batches(DEP, env)
  label <- c(
    exists = "exists (manifest.yml present), skipped",
    generate = if (DRY) "WOULD generate" else "generating",
    deferred = "deferred (grouping registry absent: run --stage gen_grouping)",
    unregistered = "NO BATCH_REGISTRY ENTRY"
  )
  for (i in seq_len(nrow(plan))) {
    say(
      "[deploy]   %-4s %-45s %s",
      plan$track[i],
      plan$batch[i],
      label[[plan$status[i]]]
    )
  }
  bad <- plan$batch[plan$status == "unregistered"]
  if (length(bad)) {
    stop(
      "[deploy] no make_batch_configs.R BATCH_REGISTRY entry for: ",
      paste(bad, collapse = ", "),
      ". Add one (see the prod_run<N> entries ",
      "near the end of the registry) or point deploy.fits.*_dir at an ",
      "existing batch dir.",
      call. = FALSE
    )
  }
  deploy_check_batch_groupings(DEP, plan)
  todo <- plan$status == "generate"
  if (!DRY && any(todo)) {
    for (b in plan$batch[todo]) {
      env$generate_batch(b)
    }
    deploy_write_provenance(
      DEP,
      CONFIG_PATH,
      stage = "gen_batches",
      inputs = .stat_inputs(file.path(plan$dir[todo], "manifest.yml")),
      generated = list(batches = plan$batch[todo])
    )
  }
  rule()
  if ("kl" %in% plan$track) {
    say(
      "Fit + compare the kl class sweep on the cluster, pin deploy.kl_sweep.cell, then derive the registry:"
    )
    say(
      "  bash analysis/bash/stages/04_fit_kl.sh --deploy %s --postprocess",
      CONFIG_PATH
    )
    say(
      "  Rscript analysis/utils/deploy_prod_run.R -C %s --stage gen_grouping",
      CONFIG_PATH
    )
    if (any(plan$status == "deferred")) {
      say(
        "  Rscript analysis/utils/deploy_prod_run.R -C %s --stage gen_batches   (the deferred fit dirs)",
        CONFIG_PATH
      )
    }
  }
  say(
    "Fit the batches on the cluster (each campaign reads its batch name from this deploy config;"
  )
  say("skip a campaign whose batch is reused from an earlier run):")
  say(
    "  bash analysis/bash/campaigns/enso_grouped_singlelag.sh --deploy %s",
    CONFIG_PATH
  )
  say(
    "  bash analysis/bash/campaigns/dur_enso_grouped_singlelag.sh --deploy %s",
    CONFIG_PATH
  )
  say(
    "  bash analysis/bash/campaigns/mon_enso_grouped_singlelag.sh --deploy %s",
    CONFIG_PATH
  )
  invisible(plan)
}

# ---------------------------------------------------------------------------
# Stage: gen_grouping  (R logic, in-process; honours --dry-run / --force)
# ---------------------------------------------------------------------------
# The fit registry deploy.grouping derived from the pinned cell of the kl
# class sweep (utils/kl_grouping.R::kl_grouping_plan_from_sweep()). Same
# side-by-side rule as gen_templates: an identical registry is left alone, a
# different one stops the stage before anything is written unless --force.
stage_gen_grouping <- function() {
  say(
    "[deploy] STAGE gen_grouping%s%s",
    if (DRY) " (dry-run)" else "",
    if (isTRUE(opt$force)) " (--force)" else ""
  )
  rule()
  ks <- DEP$kl_sweep
  if (!nzchar(ks$batch %||% "")) {
    stop(
      "[deploy] gen_grouping: deploy.kl_sweep.batch is empty -- this rollout uses the ",
      "registry '",
      DEP$grouping,
      "' as is.",
      call. = FALSE
    )
  }
  suppressPackageStartupMessages(library(dplyr))
  for (m in c("dlnm", "dlnm_kernel", "kl_grouping")) {
    source(sprintf("analysis/utils/%s.R", m))
  }
  cmp <- deploy_kl_sweep_compare_dir(DEP)
  plan <- kl_grouping_plan_from_sweep(
    cmp,
    ks$cell,
    ks$chains,
    ks$fill_from,
    ks$meta_from,
    DEP$grouping,
    DEP$fits$groups,
    fit_cmd = sprintf(
      "bash analysis/bash/stages/04_fit_kl.sh --deploy %s --postprocess",
      CONFIG_PATH
    ),
    n_agree = as.integer(ks$n_agree %||% 0L),
    mode_tol = as.numeric(ks$mode_tol %||% 1.5)
  )
  part <- plan$grouping$partition
  say("[deploy]   sweep    %s (compare: %s)", ks$batch, cmp)
  say("[deploy]   cell     %s", plan$cell)
  say("[deploy]   fit      %s", plan$fit_path)
  say(
    "[deploy]   chains   %s (kl_sweep.chains: %s%s)",
    if (length(plan$chains)) paste(plan$chains, collapse = ",") else "all",
    ks$chains,
    if (identical(ks$chains, "agree")) {
      sprintf(
        "; n_agree %s, mode_tol %s",
        ks$n_agree %||% 0L,
        ks$mode_tol %||% 1.5
      )
    } else {
      ""
    }
  )
  # Convergence of the pinned cell (deploy.convergence; off = nothing printed,
  # as before the gate): refuses BEFORE anything is written.
  conv <- kl_grouping_convergence(
    cmp,
    plan$cell,
    plan$chains,
    deploy_convergence_cfg(DEP, validate_allow = FALSE),
    dry_run = DRY,
    say = say
  )
  say(
    "[deploy]   registry %s: %s",
    registry_path(DEP$grouping),
    paste(
      sprintf("%s %d", names(table(part$group)), table(part$group)),
      collapse = ", "
    )
  )
  if (plan$grouping$n_filled > 0L) {
    say(
      "[deploy]   + %d countries carried over from %s",
      plan$grouping$n_filled,
      ks$fill_from
    )
  }
  label <- c(
    absent = if (DRY) "WOULD write (absent)" else "write (absent)",
    identical = "identical (left as is)",
    differs = "DIFFERS from the registry on disk"
  )
  say("[deploy]   status   %s", label[[plan$status]])
  if (identical(plan$status, "differs")) {
    print(plan$diff, row.names = FALSE)
  }
  if (!plan$groups_ok) {
    stop(
      "[deploy] deploy.fits.groups [",
      paste(DEP$fits$groups, collapse = ", "),
      "] does not name the derived groups. Set deploy.fits.groups: [",
      paste(plan$groups_short, collapse = ", "),
      "] (the grouping is derived; the list is ",
      "restated in the deploy YAML as a stated decision).",
      call. = FALSE
    )
  }
  if (identical(plan$status, "differs") && !isTRUE(opt$force) && !DRY) {
    stop(
      "[deploy] ",
      registry_path(DEP$grouping),
      " differs from the derived partition ",
      "(diff above); nothing written. Fits of the old registry may exist: re-run with ",
      "--force to overwrite.",
      call. = FALSE
    )
  }
  rule()
  if (DRY) {
    say("[deploy] dry-run: nothing written.")
    return(invisible(plan))
  }
  yml <- registry_path(DEP$grouping, ext = "yml")
  if (identical(plan$status, "identical") && file.exists(yml)) {
    say("[deploy] %s unchanged.", registry_path(DEP$grouping))
    return(invisible(plan))
  }
  hdr <- kl_grouping_header(
    DEP$grouping,
    CONFIG_PATH,
    ks$batch,
    plan$cell,
    plan$chains,
    plan$fit_path,
    plan$settings,
    plan$grouping$n_fit,
    plan$grouping$n_filled,
    ks$fill_from,
    ks$meta_from
  )
  out <- write_grouping_registry(
    part,
    DEP$grouping,
    plan$sidecar,
    hdr,
    plan$grouping$membership
  )
  generated <- list(
    registry = out$csv,
    sidecar = out$yml,
    membership = out$membership_csv,
    digest = out$digest,
    cell = plan$cell,
    chains = if (length(plan$chains)) plan$chains else "all"
  )
  if (!is.null(conv)) {
    generated$convergence <- list(
      action = DEP[["convergence"]][["action"]],
      verdict = conv$verdict,
      n_agree = conv$n_agree,
      refuse = as.list(conv$refuse),
      warn = as.list(conv$warn)
    )
  }
  deploy_write_provenance(
    DEP,
    CONFIG_PATH,
    stage = "gen_grouping",
    inputs = .stat_inputs(c(
      plan$fit_path,
      file.path(cmp, c("fits.csv", "loo.rds"))
    )),
    generated = generated
  )
  say("[deploy] wrote %s + %s (digest %s)", out$csv, out$yml, out$digest)
  say(
    "[deploy] Commit analysis/groupings/%s.{csv,yml} (git-tracked, written on this checkout).",
    DEP$grouping
  )
  say(
    "Next: Rscript analysis/utils/deploy_prod_run.R -C %s --stage gen_batches   (the fit dirs)",
    CONFIG_PATH
  )
  invisible(plan)
}


# Division of labour
#   * R owns all domain logic and artefact naming, run in-process (fit
#     collection, forecast / hindcast config generation, deploy <-> results
#     align, provenance).
#   * bash owns only the SLURM boundary: this script never sbatches or shells
#     out to Rscript; for HPC stages it PRINTS the `bash analysis/bash/...`
#     command to run.
#   * The deploy YAML is the only place a run is named; bash drivers read its
#     paths from `--stage resolve`. deploy_require_keys() refuses a YAML that
#     omits a run-specific key.
#   * The spatPomp templates are generated by gen_templates, never by hand.
#
# Stages (--stage), in rollout order. Writing stages honour --dry-run; an
# existing output that differs is refused unless --force.
#   gen_batches    before fitting: fit-batch (and kl sweep) config dirs from
#                  BATCH_REGISTRY; existing dirs skipped, batches whose grouping
#                  registry is not written yet deferred. Not in `all`.
#   gen_grouping   after the kl sweep: analysis/groupings/<deploy.grouping>
#                  from the pinned cell (kl_grouping.R), behind the
#                  deploy.convergence gate. Not in `all`.
#   deploy_fits    copy the per-group best-lag fits to dep$fits$dest, behind
#                  the convergence gate (fit_diagnostics_gate()).
#   gen_templates  the historical / forecast / counterfactual templates.
#   smoothing      check the historical template; PRINT the submit command.
#   gen_forecast   forecast + counterfactual configs and manifest; PRINT submit.
#   gen_attrib     attribution factual configs + manifest. Not in `all`.
#   gen_hindcast   hindcast configs + manifest; PRINT submit.
#   gen_events     past-ENSO-event attribution configs. Not in `all`.
#   align_results  point the results config at this deploy (line-level text
#                  edit, comments kept, verified after writing).
#   all            deploy_fits -> gen_templates -> smoothing, then stop (rerun
#                  gen_forecast / gen_hindcast once the smoothing cache lands).
#   resolve        read-only: the run's paths as KEY=value lines.


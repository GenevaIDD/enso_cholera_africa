# Build the event-attribution generator opt from the deploy block. Refuses an
# unset event list or a missing run-specific output key (they name a run).
.event_opt <- function() {
  ea <- DEP$event_attribution %||% list()
  events <- trimws(as.character(ea$events %||% ""))
  if (!nzchar(events)) {
    stop(
      "[deploy] gen_events: deploy.event_attribution.events is empty in ",
      CONFIG_PATH,
      ".",
      call. = FALSE
    )
  }
  for (k in c("run_tag_base", "config_outdir", "manifest")) {
    if (!nzchar(as.character(ea[[k]] %||% ""))) {
      stop(
        "[deploy] gen_events: deploy.event_attribution.",
        k,
        " is unset in ",
        CONFIG_PATH,
        " (it names a run; no default).",
        call. = FALSE
      )
    }
  }
  sem <- as.character(ea$season_end_by_group %||% "")
  # season_end "" = the hindcast's: one season-end rule per run
  # unless the deploy states otherwise.
  se_mode <- as.character(ea[["season_end"]] %||% "")
  if (!nzchar(se_mode)) {
    se_mode <- as.character(DEP$hindcast[["season_end"]] %||% "by_group")
  }
  list(
    template = DEP$templates$forecast,
    counterfactual_template = DEP$templates$counterfactual,
    events = events,
    events_registry = ea$registry %||% "analysis/configs/enso_events_v2.yml",
    analog_set = ea$analog_set %||% "neutral",
    lenssen_dir = ea$lenssen_dir %||% "generated_data/lenssen_events",
    fits_dir = DEP$fits$dest,
    grouping = DEP$grouping,
    climate_panel = ea$climate_panel,
    season_end = se_mode,
    season_min_window_months = as.integer(
      DEP$hindcast$season_min_window_months %||% 6L
    ),
    season_end_by_group = if (nzchar(sem)) {
      sem
    } else {
      DEP$hindcast$season_end_by_group
    },
    smoothing_input = DEP$smoothing_input,
    episode_key = DEP$episodes$key %||% "lp_season",
    partition_by = DEP$partition_by %||% "country",
    partition_source = DEP$partition_source %||% "",
    nbr_partition_source = .deploy_nbr_partition_source(DEP),
    run_tag_base = ea$run_tag_base,
    config_outdir = ea$config_outdir,
    manifest = ea$manifest,
    param_draw_mode = as.character(ea$param_draw_mode %||% ""),
    n_replicates = as.integer(ea[["n_replicates"]] %||% 0L),
    # Counterfactual analog matcher; NULL = legacy (no build).
    enso_counterfactual = DEP[["enso_counterfactual"]],
    enso_continuation = DEP[["enso_continuation"]],
    outdir = opt$outdir %||% "generated_data/"
  )
}

# ---------------------------------------------------------------------------
# Stage: gen_events  (R logic, in-process) -> PRINT Lenssen builds + submit cmd
# ---------------------------------------------------------------------------
stage_gen_events <- function() {
  say("[deploy] STAGE gen_events%s", if (DRY) " (dry-run)" else "")
  rule()
  o <- .event_opt()
  deploy_check_sim_template(DEP, "forecast", o$template)
  deploy_check_sim_template(DEP, "counterfactual", o$counterfactual_template)
  if (DRY) {
    say("[deploy] WOULD generate event-attribution configs:")
    say("       events        = %s", o$events)
    say(
      "       analog_set    = %s  (Lenssen caches under %s/<event>/)",
      o$analog_set,
      o$lenssen_dir
    )
    say("       climate_panel = %s", o$climate_panel)
    say(
      "       season_end    = %s%s",
      o$season_end,
      if (identical(o$season_end, "by_group")) {
        paste0(" (", o$season_end_by_group, ")")
      } else {
        sprintf(" (min window %d months)", o$season_min_window_months)
      }
    )
    say("       config_outdir = %s", o$config_outdir)
    say("       manifest      = %s", o$manifest)
    say(
      "       partition_by  = %s%s",
      o$partition_by,
      .deploy_partition_label(o)
    )
    if (nzchar(o$param_draw_mode)) {
      say("       draw mode     = %s", o$param_draw_mode)
    }
    say(
      "       replicates    = %s",
      if (o$n_replicates > 0L) o$n_replicates else "the forecast template's"
    )
    rule()
    return(invisible(TRUE))
  }
  res <- generate_event_attribution_configs(o)
  deploy_write_provenance(
    DEP,
    CONFIG_PATH,
    stage = "gen_events",
    inputs = .stat_inputs(c(
      o$template,
      o$counterfactual_template,
      o$events_registry
    )),
    generated = list(config_outdir = o$config_outdir, manifest = o$manifest)
  )
  rule()
  if (length(res$lenssen_build)) {
    say(
      "Build the per-event Lenssen caches first (local or login node; reads data/lenssen/):"
    )
    for (cmd in res$lenssen_build) {
      say("  %s", cmd)
    }
    say(
      "then re-run --stage gen_events (the manifest records each cache's status)."
    )
  }
  say("Submit the event-attribution runs on the cluster:")
  say(
    "  bash analysis/bash/stages/07_event_attribution.sh --deploy %s",
    CONFIG_PATH
  )
  deploy_emit_keys(list(
    EVENT_CONFIG_DIR = o$config_outdir,
    EVENT_MANIFEST = o$manifest,
    DEPLOY_TAG = derive_config_run_tag(CONFIG_PATH)
  ))
  invisible(TRUE)
}

# Compare deploy<->results (shared manifest) + optional align. Called after the
# gen stages, which overwrite the manifest manuscript.yml reads. The compare is
# informational here; the align (--align-results) is the same code path as
# --stage align_results, so one implementation owns the results-YAML edit.
.compare_and_align <- function(stage) {
  if (!file.exists(MANUSCRIPT_RESULTS)) {
    say(
      "[deploy] (skipping deploy<->results compare: %s not found)",
      MANUSCRIPT_RESULTS
    )
    return(invisible(NULL))
  }
  if (isTRUE(opt$align_results)) {
    say("")
    stage_align_results()
  } else {
    compare_deploy_results(CONFIG_PATH, MANUSCRIPT_RESULTS)
  }
}

# ---------------------------------------------------------------------------
# Stage: align_results  (R logic, in-process; honours --dry-run)
# ---------------------------------------------------------------------------
# Points manuscript.yml at THIS deploy (deploy_core.R::align_results_to_deploy):
# a line-level text edit of results.deploy_config + the deploy-derived
# inputs.* leaves, comments kept, verified by re-read + all-match compare. The
# pre-edit copy lands in generated_data/deploy/<stem>/, never beside the config.
stage_align_results <- function() {
  say("[deploy] STAGE align_results%s", if (DRY) " (dry-run)" else "")
  rule()
  if (!file.exists(MANUSCRIPT_RESULTS)) {
    stop(
      "[deploy] align_results: ",
      MANUSCRIPT_RESULTS,
      " not found.",
      call. = FALSE
    )
  }
  plan <- align_results_to_deploy(MANUSCRIPT_RESULTS, CONFIG_PATH, write = !DRY)
  if (!DRY && nrow(plan$changes)) {
    deploy_write_provenance(
      DEP,
      CONFIG_PATH,
      stage = "align_results",
      inputs = .stat_inputs(c(CONFIG_PATH, MANUSCRIPT_RESULTS)),
      generated = list(
        results_config = MANUSCRIPT_RESULTS,
        leaves = plan$changes$leaf
      )
    )
  }
  invisible(plan)
}

# ---------------------------------------------------------------------------
# Stage: gen_templates  (R logic, in-process; honours --dry-run / --force)
# ---------------------------------------------------------------------------
# Builds the three spatPomp templates from the skeletons + the deploy `sim:`
# overlay (deploy_core.R::deploy_plan_sim_templates()). Side-by-side rule: an
# existing template is never silently rewritten -- "unchanged" (equal but for
# simulator.run_id) is left alone, "differs" stops the stage BEFORE anything is
# written unless --force.
stage_gen_templates <- function() {
  say(
    "[deploy] STAGE gen_templates%s%s",
    if (DRY) " (dry-run)" else "",
    if (isTRUE(opt$force)) " (--force)" else ""
  )
  rule()
  plan <- deploy_plan_sim_templates(DEP)
  label <- c(
    absent = if (DRY) "WOULD write (absent)" else "write (absent)",
    unchanged = "unchanged (left as is)",
    differs = "DIFFERS from the generated template"
  )
  for (p in plan) {
    say("  %-15s %-36s %s", p$arm, label[[p$status]], p$path)
    if (identical(p$status, "differs")) {
      deploy_print_leaf_diff(
        p$diff,
        a_label = "on disk  ",
        b_label = "generated"
      )
    }
  }
  status <- vapply(plan, `[[`, "", "status")
  to_write <- names(status)[
    status == "absent" |
      (status == "differs" & isTRUE(opt$force))
  ]
  if (any(status == "differs") && !isTRUE(opt$force) && !DRY) {
    stop(
      "[deploy] gen_templates: ",
      paste(names(status)[status == "differs"], collapse = ", "),
      " template(s) differ from what the deploy YAML generates (diff above). ",
      "Nothing was written. Edit the deploy `sim:` block to reproduce them, or ",
      "re-run with --force to overwrite (a rolled-out template's smoothing cache ",
      "may already exist on the cluster).",
      call. = FALSE
    )
  }
  if (!DRY && length(to_write)) {
    for (arm in to_write) {
      deploy_write_sim_template(plan[[arm]], CONFIG_PATH)
    }
    deploy_write_provenance(
      DEP,
      CONFIG_PATH,
      stage = "gen_templates",
      inputs = .stat_inputs(c(
        vapply(names(plan), deploy_sim_skeleton_path, ""),
        CONFIG_PATH
      )),
      generated = list(
        templates = vapply(plan[to_write], `[[`, "", "path"),
        status = status
      )
    )
    say(
      "[deploy] wrote %d template(s): %s",
      length(to_write),
      paste(to_write, collapse = ", ")
    )
  }
  invisible(plan)
}


  # run_tags (deploy_core.R) -- checked before generating, dry-run included.
  deploy_check_sim_template(DEP, "forecast", o$factual_template)
  deploy_check_sim_template(DEP, "counterfactual", o$counterfactual_template)
  if (DRY) {
    say("[deploy] WOULD generate forecast + counterfactual configs:")

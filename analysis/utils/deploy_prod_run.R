say <- function(...) cat(sprintf(...), "\n", sep = "")
rule <- function() {
  say("--------------------------------------------------------------")
}

# data.frame(path, mtime, size) over existing files, for the provenance stamp.
.stat_inputs <- function(paths) {
  paths <- unique(paths[!is.na(paths) & nzchar(paths)])
  paths <- paths[file.exists(paths)]
  if (!length(paths)) {
    return(NULL)
  }
  data.frame(
    path = paths,
    mtime = format(file.mtime(paths)),
    size = file.info(paths)$size,
    stringsAsFactors = FALSE
  )
}

# ---------------------------------------------------------------------------
# Stage: deploy_fits  (R logic, in-process; honours --dry-run)
# ---------------------------------------------------------------------------
stage_deploy_fits <- function() {
  say("[deploy] STAGE deploy_fits%s", if (DRY) " (dry-run)" else "")
  rule()
  res <- deploy_collect_fits(DEP, dry_run = DRY, verbose = TRUE)
  rule()
  say(
    "[deploy] %s %d artefact(s) into %s (pruned %d).",
    if (DRY) "WOULD copy" else "copied",
    res$copied %||% nrow(res$manifest),
    res$dest,
    res$pruned %||% 0L
  )
  # Convergence gate verdict (deploy.convergence; NULL under action off, which
  # leaves the output and the provenance stamp exactly as before the gate).
  conv <- res$convergence
  if (!is.null(conv)) {
    say(
      "[deploy] convergence (%s, scope %s): %d fit(s) failed%s, %d allowed%s.",
      conv$cfg$action,
      conv$cfg$scope,
      length(conv$failed),
      if (length(conv$failed)) {
        paste0(" [", paste(conv$failed, collapse = ", "), "]")
      } else {
        ""
      },
      length(conv$allowed),
      if (length(conv$allowed)) {
        paste0(" [", paste(conv$allowed, collapse = ", "), "]")
      } else {
        ""
      }
    )
  }
  if (!DRY) {
    deployed <- file.path(res$dest, res$manifest$file)
    generated <- list(dest = res$dest, n_fits = nrow(res$manifest))
    if (!is.null(conv)) {
      generated$convergence <- list(
        action = conv$cfg$action,
        scope = conv$cfg$scope,
        thresholds = list(
          rhat_max = conv$cfg$rhat_max,
          ess_min = conv$cfg$ess_min,
          max_divergent = conv$cfg$max_divergent,
          rhat_any = conv$cfg$rhat_any,
          ebfmi_min = conv$cfg$ebfmi_min
        ),
        failed = as.list(conv$failed),
        allowed = as.list(conv$allowed)
      )
    }
    deploy_write_provenance(
      DEP,
      CONFIG_PATH,
      stage = "deploy_fits",
      inputs = .stat_inputs(c(
        deployed,
        file.path(res$dest, "MANIFEST.csv"),
        if (!is.null(conv)) file.path(res$dest, "CONVERGENCE.csv")
      )),
      generated = generated
    )
  }
  invisible(res)
}

# ---------------------------------------------------------------------------
# Stage: smoothing  (assert template consistency + PRINT submit cmd; no sbatch)
# ---------------------------------------------------------------------------
stage_smoothing <- function() {
  say("[deploy] STAGE smoothing (assert + print submit cmd; NO sbatch)")
  rule()
  # run_tag, nbr_contagion gate, episodes.key, fits dir (deploy_core.R). The
  # template is generated by gen_templates; this re-checks what is ON DISK, so
  # a template edited behind the generator's back is still caught.
  tpl <- DEP$templates$historical
  thist <- deploy_check_sim_template(DEP, "historical", tpl)
  got_tag <- thist$simulator$run_tag
  nbr_on <- isTRUE(thist$simulator$nbr_contagion$enable)
  ep_key <- DEP$episodes$key %||% "lp_season"
  preflight_sim_episode_inputs(thist, label = "historical smoothing template")
  # The smoothing partition is the historical template's filter.partition_by,
  # set by the deploy's sim.historical overlay and deliberately decoupled from
  # DEP$partition_by (a FORWARD/hindcast setting): a region-forward rollout can
  # still smooth per-country and assemble the region IC forward. Echo the
  # template's smoothing partition so the operator can see which one will run.
  tpl_part <- thist$simulator$filter$partition_by %||% "transmission_unit"
  say(
    "[deploy] historical template OK: run_tag=%s nbr_contagion.enable=%s smoothing_partition=%s episodes.key=%s",
    got_tag,
    nbr_on,
    tpl_part,
    ep_key
  )
  rule()
  say("Run the historical smoothing on the cluster:")
  say("  bash analysis/bash/stages/08_smoothing.sh --config %s", tpl)
  invisible(TRUE)
}

# Neighbour-contagion partition registry for the generated sim configs of a
# registry-partitioned deploy (NULL otherwise: nothing is written).
.deploy_nbr_partition_source <- function(dep) {
  if (!identical(dep$partition_by %||% "country", "registry")) {
    return(NULL)
  }
  deploy_nbr_partition_source(dep) # deploy_core.R: contagion registry, else the partition one
}
# " (registry <source>: units ...)" for dry-run lines, "" otherwise.
.deploy_partition_label <- function(o) {
  if (!identical(o$partition_by, "registry")) {
    return("")
  }
  sprintf(
    " (source %s; contagion %s)",
    o$partition_source,
    o$nbr_partition_source %||% o$partition_source
  )
}
# Region / registry deploys pass --partition_by so the submitter runs one task
# per config (a unit couples its countries); country deploys print the flag-free
# command unchanged.
.deploy_part_flag <- function(o) {
  if (o$partition_by %in% c("enso_region", "registry")) {
    paste0(" --partition_by ", o$partition_by)
  } else {
    ""
  }
}


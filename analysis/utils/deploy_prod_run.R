        "       enso_continuation = %s%s",
        o$enso_continuation$method,
        if (identical(o$enso_continuation$method, "analog")) {
          sprintf(
            " (library %s, k %s, blend %s mo, min_sep %s, max_per_model %s, exclude %s)",
            o$enso_continuation[["library"]],
            o$enso_continuation[["k"]],
            o$enso_continuation[["blend_months"]],
            o$enso_continuation[["min_sep"]],
            o$enso_continuation[["max_per_model"]] %||% Inf,
            if (length(unlist(o$enso_continuation[["exclude_models"]]))) {
              paste(
                unlist(o$enso_continuation[["exclude_models"]]),
                collapse = ","
              )
            } else {
              "none"
            }
          )
        } else {
          ""
        }
      )
    }
    say("       episodes.key  = %s", o$episode_key)
  } else {
    generate_forecast_configs(o)
    deploy_write_provenance(
      DEP,
      CONFIG_PATH,
      stage = "gen_forecast",
      inputs = .stat_inputs(c(
        o$factual_template,
        o$counterfactual_template,
        o$manifest
      )),
      generated = list(config_outdir = o$config_outdir, manifest = o$manifest)
    )
  }
  rule()
  # Region deploys pass --partition_by enso_region so the submitter runs one task
  # per config; country deploys print the flag-free command unchanged.
  part_flag <- .deploy_part_flag(o)
  say("Submit the forecast rollout on the cluster:")
  say(
    "  bash analysis/bash/stages/07_forecast_groups.sh --config-dir %s%s",
    o$config_outdir,
    part_flag
  )
  deploy_emit_keys(list(
    CONFIG_DIR = o$config_outdir,
    MANIFEST = o$manifest,
    DEPLOY_TAG = derive_config_run_tag(CONFIG_PATH)
  ))
  if (!DRY) {
    .compare_and_align("gen_forecast")
  }
  invisible(TRUE)
}

# ---------------------------------------------------------------------------
# Stage: gen_attrib  (R logic, in-process) -> PRINT the attribution-arm submit cmd
# ---------------------------------------------------------------------------
# The attribution factual: the forecast manifest's
# factual configs launched at the counterfactual handoff, so factual and
# counterfactual share the smoothing replicate, posterior draw and seed of
# every replicate. Reads the manifest gen_forecast wrote; the forecast and
# counterfactual configs are not touched.
stage_gen_attrib <- function() {
  say("[deploy] STAGE gen_attrib%s", if (DRY) " (dry-run)" else "")
  rule()
  am <- as.character(DEP$outputs$forecast_attrib_manifest %||% "")
  if (!nzchar(am)) {
    say(
      "[deploy] deploy.outputs.forecast_attrib_manifest is unset: no attribution factual (nothing to do)."
    )
    rule()
    return(invisible(FALSE))
  }
  o <- list(
    manifest = DEP$outputs$forecast_manifest,
    attrib_manifest = am,
    dry_run = DRY,
    force = isTRUE(opt$force)
  )
  res <- generate_forecast_attrib_configs(o)
  if (!DRY) {
    deploy_write_provenance(
      DEP,
      CONFIG_PATH,
      stage = "gen_attrib",
      inputs = .stat_inputs(c(o$manifest, unlist(res$configs))),
      generated = list(config_outdir = res$config_dir, manifest = am)
    )
  }
  rule()
  if (isTRUE(res$aligned)) {
    say(
      "The factual already launches at the counterfactual handoff: no attribution arm to submit."
    )
  } else {
    say(
      "Submit the attribution factual on the cluster (no --chunk_size: the chunk enters the seed):"
    )
    say(
      "  bash analysis/bash/stages/07_forecast_groups.sh --deploy %s --arm attrib --postprocess",
      CONFIG_PATH
    )
  }
  deploy_emit_keys(list(
    CONFIG_DIR = res$config_dir,
    ATTRIB_MANIFEST = am,
    DEPLOY_TAG = derive_config_run_tag(CONFIG_PATH)
  ))
  invisible(TRUE)
}

